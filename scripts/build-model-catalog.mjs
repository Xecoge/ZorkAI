// Regenerates lib/ai/catalog.ts from the live Drake gateway model list.
// Usage: DRAKE_API_KEY=... node scripts/build-model-catalog.mjs
// The output is real gateway data (ids + context length); display names are
// derived from the ids, vendor prefixes are dropped because the picker shows
// names only. Rerun whenever the gateway adds or retires models.
import fs from "node:fs";

const BASE = process.env.DRAKE_BASE_URL ?? "https://api.drakezakuru.com/v1";
const KEY = (process.env.DRAKE_API_KEY || process.env.API_KEY || "").trim();
if (!KEY) {
  console.error("Set DRAKE_API_KEY (or API_KEY) first.");
  process.exit(1);
}

const res = await fetch(`${BASE.replace(/\/$/, "")}/models`, {
  headers: { Authorization: `Bearer ${KEY}` },
});
if (!res.ok) {
  console.error(`Gateway answered ${res.status}`);
  process.exit(1);
}
const payload = await res.json();
const rows = Array.isArray(payload?.data) ? payload.data : [];

const ACRONYMS = new Map([
  ["gpt", "GPT"],
  ["oss", "OSS"],
  ["ai", "AI"],
  ["vl", "VL"],
  ["moe", "MoE"],
  ["llm", "LLM"],
  ["api", "API"],
  ["glm", "GLM"],
  ["tts", "TTS"],
  ["asr", "ASR"],
  ["ocr", "OCR"],
  ["deepseek", "DeepSeek"],
  ["minimax", "MiniMax"],
  ["internlm", "InternLM"],
  ["sdxl", "SDXL"],
]);

// Pools that cannot answer a chat completion (speech, images, embeddings,
// rerankers, moderation). Offering them in the picker would only produce errors.
const NON_CHAT = /(^|[-/_])(tts|asr|whisper|speech|audio|transcribe|embed|embedding|rerank|moderation|dall-e|dalle|imagen|image|flux|sdxl|stable-diffusion|midjourney|video|veo|sora|kling|recraft|ocr)([-/_]|$)/i;

const NAME_OVERRIDES = new Map([
  ["guava3/claude-sonnet-4-6", "Claude Sonnet 4.6"],
  ["lime23/anthropic/claude-fable-5", "Claude Fable 5"],
  ["lime23/anthropic/claude-fable-5-1", "Claude Fable 5.1"],
  ["lime23/anthropic/claude-fable-5-2", "Claude Fable 5.2"],
  ["lime23/anthropic/claude-haiku-4-5-20251001", "Claude Haiku 4.5"],
  ["lime23/anthropic/claude-haiku-5-5", "Claude Haiku 5.5"],
  ["guava3/claude-sonnet-4-6", "Claude Sonnet 4.6"],
]);

function displayName(id) {
  if (NAME_OVERRIDES.has(id)) return NAME_OVERRIDES.get(id);
  let tail = id.replace(/:free$/, "");
  const parts = tail.split("/");
  tail = parts[parts.length - 1];
  const raw = tail.split(/[-_]+/).filter(Boolean);
  const out = [];
  for (let i = 0; i < raw.length; i++) {
    const token = raw[i];
    if (/^\d+$/.test(token)) {
      // Merge a run of single-digit numbers into a dotted version (4-6 -> 4.6).
      let j = i;
      const run = [];
      while (j < raw.length && /^\d$/.test(raw[j])) run.push(raw[j++]);
      if (run.length >= 2 && run.length <= 3) {
        out.push(run.join("."));
        i = j - 1;
        continue;
      }
      out.push(token);
      continue;
    }
    if (ACRONYMS.has(token.toLowerCase())) {
      out.push(ACRONYMS.get(token.toLowerCase()));
      continue;
    }
    out.push(token.charAt(0).toUpperCase() + token.slice(1));
  }
  return out.join(" ").replace(/\bB\b$/, "B");
}

function looksFree(id) {
  return id.startsWith("free/") || id.endsWith(":free") || /free/i.test(id.split("/")[0]);
}

function priceFor(id) {
  const lower = id.toLowerCase();
  if (looksFree(id)) return [0.01, 0.02];
  if (/claude|gpt-5|grok|opus|sonnet|fable|gemini-3\.8/.test(lower)) return [0.15, 0.6];
  return [0.05, 0.15];
}

const seen = new Set();
const rowsOut = [];
const ids = rows
  .map((m) => ({ id: String(m.id ?? ""), ctx: Number(m.context_length ?? m.context_window ?? 0) || 0 }))
  .filter((m) => Boolean(m.id))
  .filter((m) => !NON_CHAT.test(m.id.replace(/^[^/]+\//, "").replace(/:free$/, "")))
  .sort((a, b) => a.id.length - b.id.length || a.id.localeCompare(b.id));

for (const { id, ctx } of ids) {
  const name = displayName(id).trim();
  if (!name || seen.has(name.toLowerCase())) continue;
  seen.add(name.toLowerCase());
  const [inK, outK] = priceFor(id);
  const lower = id.toLowerCase();
  const vision = /\bvl\b|vision|omni|image|gemini|gpt-5|claude|grok|qwen.*vl/.test(lower) ? 1 : 0;
  const reasoning = /reason|thinking|o3|o4|r1|deepseek-r/.test(lower) ? 1 : 0;
  rowsOut.push([id, name, id.split("/")[0], inK, outK, ctx || 131_072, vision, reasoning]);
}

const lines = rowsOut.map(
  (r) => `  ${JSON.stringify(r)},`,
);

const file = `// GENERATED by scripts/build-model-catalog.mjs — do not edit by hand.
// Every id below comes from GET {DRAKE_BASE_URL}/models (snapshot 2026-11-27).
// Tuple: [gatewayId, displayName, pool, creditsPer1kIn, creditsPer1kOut, contextLength, vision, reasoning]
export type CatalogRow = [string, string, string, number, number, number, number, number];

export const CATALOG: CatalogRow[] = [
${lines.join("\n")}
];
`;

fs.writeFileSync("lib/ai/catalog.ts", file);
console.log(`wrote lib/ai/catalog.ts with ${rowsOut.length} models`);
